-- Reference data for the dataset/release module (0047_add_dataset_module_tables).
--
-- These four tables are lookups, not test data: the module cannot function
-- without them. A dataset needs a type, a recordset needs a type, and a
-- transfer needs a destination -- all NOT NULL foreign keys.
--
-- recordset_license and transfer_mode were removed 2026-09-01: licensing is
-- WordPress's to own, and transfer_mode was never shown to curators because
-- each destination always uses the same mode.
--
-- The ids are contract values, not display labels, so they are supplied
-- explicitly rather than left to the identity sequences. Several are matched
-- from application code:
--
--   * transfer_destination.destination_abbr -- 'idc' selects the IDC fan-out in
--     _fan_out_transfer_files, gates the transfer daemon's reconciler and claim,
--     and keys the cycle UI's manifest grouping.
--   * recordset_type.recordset_type_name    -- IDC_CLINICAL_PREDICATE compares
--     against the literal 'Clinical Data'. Renaming that row silently stops
--     clinical files being routed to IDC.
--
-- Renaming or renumbering either of those is a code change, not a data edit.
--
-- Idempotent by primary key, so it is safe on a database that already holds
-- these rows from the pre-migration seed script. That only protects against
-- duplicates: a database that already has these *names* under different ids has
-- diverged from the contract above and needs fixing by hand, not by re-running
-- this.
--
-- No BEGIN/COMMIT -- ./migrate wraps each migration in --single-transaction.

INSERT INTO public.dataset_type (dataset_type_id, dataset_type_name) VALUES
    (1, 'Collection'),
    (2, 'Analysis Result')
ON CONFLICT (dataset_type_id) DO NOTHING;

INSERT INTO public.recordset_type (recordset_type_id, recordset_type_name) VALUES
    (1, 'Radiology Images'),
    (2, 'Histopathology Images'),
    (3, 'Image Annotations'),
    (4, 'Clinical Data'),
    (5, 'Other')
ON CONFLICT (recordset_type_id) DO NOTHING;

INSERT INTO public.transfer_destination
    (destination_id, destination_name, destination_abbr) VALUES
    (1, 'Imaging Data Commons', 'idc'),
    (2, 'General Commons',      'gc'),
    (3, 'WordPress',            'wp'),
    (4, 'Aspera Faspex',        'asp'),
    (5, 'NBIA',                 'nbia')
ON CONFLICT (destination_id) DO NOTHING;

INSERT INTO public.dataset_relation_type
    (relation_type_id, forward_label, reverse_label) VALUES
    (1, 'isDerivedFrom', 'isSourceOf')
ON CONFLICT (relation_type_id) DO NOTHING;

-- The id columns are GENERATED BY DEFAULT AS IDENTITY, so supplying ids above
-- leaves each sequence still pointing at 1. Without this the first row added
-- through the UI collides with a seeded id.
SELECT setval(pg_get_serial_sequence('public.dataset_type', 'dataset_type_id'),
              (SELECT max(dataset_type_id) FROM public.dataset_type));
SELECT setval(pg_get_serial_sequence('public.recordset_type', 'recordset_type_id'),
              (SELECT max(recordset_type_id) FROM public.recordset_type));
SELECT setval(pg_get_serial_sequence('public.transfer_destination', 'destination_id'),
              (SELECT max(destination_id) FROM public.transfer_destination));
SELECT setval(pg_get_serial_sequence('public.dataset_relation_type', 'relation_type_id'),
              (SELECT max(relation_type_id) FROM public.dataset_relation_type));
