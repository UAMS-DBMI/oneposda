# Builds the difference reports for a finished distributed edit and offers the
# user the accept/reject buttons.
#
# This is the AtTheEnd routine of BackgroundEditorTp.pl, lifted into a job of
# its own. There it had to run inside the same process that performed the edits,
# which is precisely the process that must be allowed to die; here the worker
# that wins the "comparisons complete" transition queues this, so the reports
# survive a worker being killed and can be regenerated by re-queueing.
#
use strict;
use Posda::DB 'Query';
use Posda::BackgroundProcess;

$| = 1;

my $usage = <<USAGE_END;
EditReportsTp.pl <?bkgrnd_id?> <activity_id> <subprocess_invoc_id> <notify>
or
EditReportsTp.pl -h

Generates the EditDifferences, ShortEditDifferences and error reports for the
edit run identified by <subprocess_invoc_id>, and attaches the buttons that
accept or reject the edits.
USAGE_END

if($#ARGV == 0 && $ARGV[0] eq "-h"){ print $usage; exit }
unless($#ARGV == 3){
  print "Error: wrong number of args\n$usage\n";
  die "$usage\n";
}
my($invoc_id, $activity_id, $subproc_invoc_id, $notify) = @ARGV;

my $background = Posda::BackgroundProcess->new($invoc_id, $notify, $activity_id);
$background->Daemonize;

my $rpt_pipe = $background->CreateReport("EditDifferences");
$rpt_pipe->print("\"Short Report\"," .
  "\"Long Report\",\"short_file_id\",\"long_file_id\",\"num_files\"\r\n");
my $rpt_pipe1 = $background->CreateReport("ShortEditDifferences");
$rpt_pipe1->print("\"Short Report\"," .
  "\"short_file_id\",\"num_files\"\r\n");
my $rpt_pipe_err = $background->CreateReport("Errors in Edits");
$rpt_pipe_err->print("\"sop_instance_uid\",\"state\",\"attempts\",\"message\"\r\n");

#############################
# Report file contents, by file_id.
#
# The original shelled out to `cat $file` once per row -- a fork and exec of
# /bin/sh for every distinct report, with the path interpolated unquoted -- and
# then read every short report a second time to build the summary. Read them
# directly and remember what we have read.
my $get_path = Query("GetFilePath");
my %TextById;
sub report_text {
  my($file_id) = @_;
  return $TextById{$file_id} if exists $TextById{$file_id};
  my $path;
  $get_path->RunQuery(sub {
    my($row) = @_;
    $path = $row->[0];
  }, sub {}, $file_id);
  my $text = "";
  if(defined $path and open(my $fh, '<', $path)){
    local $/;
    $text = <$fh>;
    close $fh;
    $text = "" unless defined $text;
    chomp $text;
  }
  $TextById{$file_id} = $text;
  return $text;
}

sub csv_quote {
  my($v) = @_;
  $v = "" unless defined $v;
  $v =~ s/"/""/g;
  return $v;
}

#############################
# Errors, straight from the task table. The single-process version could only
# report what was still in its memory; these are durable.
my $num_errors = 0;
Query("EditTaskErrorsForEdit")->RunQuery(sub {
  my($row) = @_;
  my($sop, $state, $attempts, $error) = @$row;
  $num_errors += 1;
  $rpt_pipe_err->print("\"" . csv_quote($sop) . "\",\"" . csv_quote($state) .
    "\",$attempts,\"" . csv_quote($error) . "\"\r\n");
}, sub {}, $subproc_invoc_id);

#############################
# Difference reports.
#
# DifferenceReportByEditId already groups by (short_report_file_id,
# long_report_file_id), so the number of rows is bounded by the number of
# distinct diff patterns, not by the number of files. Rows are streamed to the
# report as they arrive rather than accumulated in a hash first.
my %ShortTotals;
my %ShortSeen;
my $num_rows = 0;
Query("DifferenceReportByEditId")->RunQuery(sub {
  my($row) = @_;
  my($short_id, $long_id, $num_files) = @$row;
  $num_rows += 1;

  # The long report is what distinguishes the rows; the short one repeats for
  # every long variant under it, so print it only the first time, as before.
  my $short_rept = $ShortSeen{$short_id} ? "-" : report_text($short_id);
  $ShortSeen{$short_id} = 1;
  my $long_rept = report_text($long_id);

  $rpt_pipe->print("\"" . csv_quote($short_rept) . "\",\"" .
    csv_quote($long_rept) . "\",$short_id,$long_id,$num_files\r\n");

  $ShortTotals{$short_id} += $num_files;
}, sub {}, $subproc_invoc_id);

for my $short_id (sort { $a <=> $b } keys %ShortTotals){
  $rpt_pipe1->print("\"" . csv_quote(report_text($short_id)) .
    "\",$short_id,$ShortTotals{$short_id}\r\n");
}

#############################
# Accept / reject.
my $param_hash = {
  op => "OpenTableFreePopup",
  class_ => "Posda::NewerProcessPopup",
  cap_ => "RejectEditsTp",
  # The original passed command => "ImportEditsTp" on the reject button, which
  # named the accept operation on the button that rejects.
  command => "RejectEditsTp",
  subprocess_invoc_id => $subproc_invoc_id,
  activity_id => $activity_id,
  notify => $notify
};
$background->InsertEmailButton(
  "Reject Edits and Delete Temporary Files", "ScriptButton", $param_hash);

$param_hash = {
  op => "OpenTableFreePopup",
  class_ => "Posda::NewerProcessPopup",
  cap_ => "ImportEditsTp",
  command => "ImportEditsTp",
  subprocess_invoc_id => $subproc_invoc_id,
  activity_id => $activity_id,
  notify => $notify
};
$background->InsertEmailButton(
  "Accept Edits, Import and Delete Temporary Files", "ScriptButton", $param_hash);

#############################
my %counts;
Query("EditTaskStateCounts")->RunQuery(sub {
  my($row) = @_;
  $counts{$row->[0]} = $row->[1];
}, sub {}, $subproc_invoc_id);
my $changed   = $counts{compared}  || 0;
my $unchanged = $counts{unchanged} || 0;

$background->WriteToEmail(
  "Edits complete for subprocess_invocation_id $subproc_invoc_id\n" .
  "  changed:            $changed\n" .
  "  unchanged:          $unchanged\n" .
  "  errors:             $num_errors\n" .
  "  distinct diffs:     $num_rows\n\n" .
  "Use the buttons below to accept or reject these edits.\n");

$background->Finish(
  "Done: $changed changed, $unchanged not changed, $num_errors errors");
exit;
