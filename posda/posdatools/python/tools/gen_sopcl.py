"""Generate the SOP class description table from DataDict.pm's $SopCl.

This is the table FastFileProcessWorker.pl consults for
`dicom_file.dicom_file_type`, and it is NOT the same as the `name` fields in
DicomIod.pm's $SopHandlers -- 41 of 81 entries disagree.
"""

import re
from pathlib import Path

# tools/ -> python/ -> posdatools/
POSDATOOLS = Path(__file__).resolve().parents[2]

SRC = POSDATOOLS / "Posda/include/Posda/DataDict.pm"

text = SRC.read_text()
block = text[text.index("$SopCl = {") :]
block = block[: block.index("\n};")]

# Match each "uid" => { ... } record, then pull sopcl_desc out of the body
# regardless of field order.
RECORD_RE = re.compile(r'"([0-9.]+)"\s*=>\s*\{(.*?)\n  \}', re.DOTALL)
DESC_RE = re.compile(r'"sopcl_desc"\s*=>\s*"((?:[^"\\]|\\.)*)"')


def unescape_perl(text: str) -> str:
    """Undo escaping inside a Perl double-quoted string.

    Only backslash-escaped literals appear here (\\" and \\@); a backslash
    before anything else simply drops out.
    """
    return re.sub(r"\\(.)", r"\1", text)


records = RECORD_RE.findall(block)
total_desc = block.count("sopcl_desc")
print(f"records matched: {len(records)}; sopcl_desc occurrences: {total_desc}")

table: dict[str, str] = {}
missing = []
for uid, body in records:
    match = DESC_RE.search(body)
    if match is None:
        missing.append(uid)
        continue
    table[uid] = unescape_perl(match.group(1))

print(f"extracted: {len(table)}; records without a description: {len(missing)}")
if missing:
    print("  ", missing[:10])

lines = [
    '"""SOP class descriptions, generated from Posda::DataDict\'s $SopCl.',
    "",
    "This is the table ``FastFileProcessWorker.pl`` uses to fill",
    "``dicom_file.dicom_file_type``. It is deliberately *not* the ``name``",
    "field of DicomIod.pm's handler table: 41 of the 81 SOP classes with",
    "handlers carry a different string there, so using the wrong one would",
    "change dicom_file_type for half of them.",
    "",
    "Generated by scratchpad/gen_sopcl.py; regenerate if DataDict.pm changes.",
    '"""',
    "",
    "SOP_CLASS_DESCRIPTIONS: dict[str, str] = {",
]
for uid in sorted(table, key=lambda u: [int(p) for p in u.split(".")]):
    desc = table[uid].replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'    "{uid}": "{desc}",')
lines.append("}")
lines.append("")
lines.append("")
lines.append("def sop_class_description(sop_class: str) -> str:")
lines.append('    """Description for a SOP class UID, or the UID itself.')
lines.append("")
lines.append("    Mirrors the Perl's fallback: an unknown UID is stored verbatim.")
lines.append('    """')
lines.append("    return SOP_CLASS_DESCRIPTIONS.get(sop_class, sop_class)")

out = POSDATOOLS / "python/posda/ingest/sopclasses.py"
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} with {len(table)} entries")
