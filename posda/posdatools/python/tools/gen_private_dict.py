"""Generate the private-tag VM/VR table from Posda's PvtDataDict.pm.

Posda decides array-ness from the dictionary VM for private elements just as
it does for public ones, so without this table every private read comes back
as a list and columns that expect a scalar break. 11,444 entries across 501
private creators, which is far too many to transcribe.

Only VM and VR are carried over; the names are not used by the ingest path.
"""

import re
from pathlib import Path

POSDATOOLS = Path(__file__).resolve().parents[2]
SRC = POSDATOOLS / "Posda/include/Posda/PvtDataDict.pm"
OUT = POSDATOOLS / "python/posda/ingest/privatedict.py"

ENTRY_RE = re.compile(
    r'\$Posda::DataDict::PvtDict->\{"((?:[^"\\]|\\.)*)"\}'
    r"->\{(\d+)\}->\{(\d+)\} = \{(.*?)\n\};",
    re.DOTALL,
)
FIELD_RE = re.compile(r'"(\w+)"\s*=>\s*"((?:[^"\\]|\\.)*)"')


def unescape(text: str) -> str:
    return re.sub(r"\\(.)", r"\1", text)


text = SRC.read_text(errors="replace")
entries = ENTRY_RE.findall(text)
print(f"entries matched: {len(entries)}")

table: dict[str, dict[tuple[int, int], tuple[str, str]]] = {}
for creator, group, element, body in entries:
    fields = dict(FIELD_RE.findall(body))
    vm = fields.get("VM")
    vr = fields.get("VR")
    if vm is None or vr is None:
        continue
    table.setdefault(unescape(creator), {})[(int(group), int(element))] = (vm, vr)

total = sum(len(v) for v in table.values())
print(f"creators: {len(table)}, tags: {total}")

lines = [
    '"""Private-tag VM/VR, generated from Posda::DataDict\'s $PvtDict.',
    "",
    "Posda applies the dictionary VM to private elements exactly as it does",
    "to public ones, so a private tag declared VM 1 comes back as a scalar",
    "while an unknown one is treated as multi-valued. Reproducing that is the",
    "only way private reads land in the right columns.",
    "",
    "Keys are (group, element-within-block); the element is the low byte of",
    "the private tag, which is what Posda's signature syntax names.",
    "",
    "Generated by tools/gen_private_dict.py; regenerate if PvtDataDict.pm",
    "changes.",
    '"""',
    "",
    "PRIVATE_DICT: dict[str, dict[tuple[int, int], tuple[str, str]]] = {",
]
for creator in sorted(table):
    escaped = creator.replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'    "{escaped}": {{')
    for key in sorted(table[creator]):
        vm, vr = table[creator][key]
        lines.append(f'        ({key[0]}, {key[1]}): ("{vm}", "{vr}"),')
    lines.append("    },")
lines.append("}")
lines.append("")
lines.append("")
lines.append("def private_vm_vr(")
lines.append("    creator: str, group: int, element: int")
lines.append(") -> tuple[str, str] | None:")
lines.append('    """VM and VR for a private tag, or None if undeclared."""')
lines.append("    return PRIVATE_DICT.get(creator, {}).get((group, element))")

OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT}")
